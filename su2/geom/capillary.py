"""gmsh .geo for an axisymmetric capillary exhausting into a chamber.

x is the symmetry axis, y is radius, exit plane at x = 0. Units: metres.

  P5 +--------------- top (outlet) --------------+ P4
     |                                           |
 faceplate              block B               outlet
     |                                           |
  P7 +---- tube wall ----+ P6 ------------------+ P8
     |                   |                       |
   inlet   tube block    |       block A       outlet
     |                   |                       |
  P1 +------ axis -------+ P2 ------ axis ------+ P3

Markers: inlet, wall, faceplate, axis, outlet
"""
from lib.common import die, fmt, get, growth_rate


def geo(case: dict, source: str = "") -> str:
    """Return the .geo file text for this case. `source` is noted in the header."""
    D = get(case, "geometry", "throat_diam_mm") * 1e-3
    L = get(case, "geometry", "throat_length_mm") * 1e-3
    R = D / 2
    Lx = get(case, "geometry", "chamb_length_cm") * 1e-2
    Rext = get(case, "geometry", "chamb_height_cm") * 1e-2
    h = get(case, "su2", "first_cell_um") * 1e-6
    nr_t = get(case, "su2", "n_radial_tube")
    nx_t = get(case, "su2", "n_axial_tube")
    nx_e = get(case, "su2", "n_axial_ext")
    nr_e = get(case, "su2", "n_radial_ext")

    if not Rext > R:
        die("geometry.chamb_height_cm must exceed the throat radius")

    # Every graded line is oriented so it starts at the fine end; gmsh then
    # grows cell size by the progression factor along the line.
    g_rt = growth_rate(R, nr_t, h)
    g_xt = growth_rate(L, nx_t, h)
    g_xe = growth_rate(Lx, nx_e, h)
    g_re = growth_rate(Rext - R, nr_e, h)

    points = {
        1: (-L, 0), 2: (0, 0), 3: (Lx, 0), 4: (Lx, Rext),
        5: (0, Rext), 6: (0, R), 7: (-L, R), 8: (Lx, R),
    }

    out = [
        f"// Generated by su2/geom/capillary.py from {source}",
        f"// D = {fmt(D)} m, L = {fmt(L)} m, domain {fmt(Lx)} x {fmt(Rext)} m, "
        f"first cell {fmt(h)} m",
        f"// growth: tube radial {g_rt:.8f}, tube axial {g_xt:.8f}, "
        f"ext axial {g_xe:.8f}, ext radial {g_re:.8f}",
        "",
    ]
    out += [f"Point({i}) = {{{fmt(x)}, {fmt(y)}, 0}};" for i, (x, y) in points.items()]
    out.append("""
// tube (axial lines run exit -> inlet, radial lines run wall -> axis)
Line(1) = {2, 1};   // axis, tube
Line(2) = {6, 7};   // tube wall
Line(3) = {7, 1};   // inlet
Line(4) = {6, 2};   // exit plane
// block A (exit plane -> outlet, lip radius -> axis)
Line(5) = {2, 3};   // axis, chamber
Line(6) = {6, 8};   // lip line extension
Line(7) = {8, 3};   // outlet, lower
// block B (lip -> outer radius)
Line(8) = {6, 5};   // faceplate
Line(9) = {8, 4};   // outlet, upper
Line(10) = {5, 4};  // top

Curve Loop(1) = {-1, -4, 2, 3};
Curve Loop(2) = {5, -7, -6, 4};
Curve Loop(3) = {6, 9, -10, -8};
Plane Surface(1) = {1};
Plane Surface(2) = {2};
Plane Surface(3) = {3};
""")
    out += [
        f"Transfinite Curve{{3, 4, 7}} = {nr_t + 1} Using Progression {g_rt:.8f};",
        f"Transfinite Curve{{1, 2}} = {nx_t + 1} Using Progression {g_xt:.8f};",
        f"Transfinite Curve{{5, 6, 10}} = {nx_e + 1} Using Progression {g_xe:.8f};",
        f"Transfinite Curve{{8, 9}} = {nr_e + 1} Using Progression {g_re:.8f};",
    ]
    out.append("""Transfinite Surface{1, 2, 3};
Recombine Surface{1, 2, 3};

Physical Curve("inlet") = {3};
Physical Curve("wall") = {2};
Physical Curve("faceplate") = {8};
Physical Curve("axis") = {1, 5};
Physical Curve("outlet") = {7, 9, 10};
Physical Surface("fluid") = {1, 2, 3};
""")
    return "\n".join(out)
