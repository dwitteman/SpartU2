#!/usr/bin/env python3
"""Build an SU2 run directory from a case file: mesh + config.

Usage: python su2/setup.py [CASE.toml] [--runs RUNS_DIR]
Creates RUNS_DIR/<case name>/su2/ (CASE defaults to config.toml, RUNS_DIR to ./runs).
"""
import argparse
import importlib
import re
import shutil
import subprocess
import sys
from pathlib import Path

if __package__ in (None, ""):  # allow `python su2/setup.py` as well as `-m su2.setup`
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from lib.common import die, fmt, get, load_case, log

# Continuum gas properties, keyed by the species file stem (sparta/data/<key>.species/.vss).
# he, ar: Sutherland matched to the DSMC VSS viscosity at 273 K only. It is 16-60% low
#   below ~100 K, where the VSS power law and Sutherland's law diverge.
# d2: Sutherland minimax-fitted to the d2.vss viscosity over 20-400 K (max error 7.2%
#   anywhere in that range), since nozzle expansions reach those temperatures. Anchoring
#   at room temperature instead (S = 57 K) would be <1% there but 51% low at 20 K. SU2 only allows Sutherland or
#   constant viscosity with the compressible solver, so a power law can't be matched exactly.
#   gamma = 1.4 assumes active rotation (D2 theta_rot = 43 K); below ~50 K rotation freezes
#   and the real gamma rises towards 5/3. Pr ~ 0.71 (hydrogen-like diatomic).
# n2: Sutherland minimax-fitted to the n2.vss viscosity over 50-400 K (max error 4.7%).
#   Below ~50 K an N2 expansion is supersaturated/condensing and the ideal-gas model fails
#   anyway; fitting down to 20 K would cost 9.3%. (Literature S = 107 K follows real N2 but
#   not the VSS power law below ~150 K.) gamma = 1.4 (theta_rot = 2.9 K, vibration frozen).
GASES = {
    #     gamma     R [J/kg/K] mu_ref    T_ref   S      Pr
    "he": dict(gamma=1.666667, R=2077.1, mu_ref=1.865e-5, T_ref=273.15, S=79.4, Pr=0.667),
    "ar": dict(gamma=1.666667, R=208.13, mu_ref=2.125e-5, T_ref=273.15, S=144.0, Pr=0.667),
    "d2": dict(gamma=1.4, R=2064.06, mu_ref=1.1716e-5, T_ref=273.15, S=14.5, Pr=0.71),
    "n2": dict(gamma=1.4, R=296.80, mu_ref=1.6616e-5, T_ref=273.15, S=40.75, Pr=0.71),
}


def write_mesh(case: dict, case_path: Path, run_dir: Path):
    """Write mesh.geo with the nozzle's geometry generator, then mesh it with gmsh."""
    noz = get(case, "geometry", "noz_type")
    try:
        gen = importlib.import_module(f"su2.geom.{noz}")
    except ModuleNotFoundError:
        die(f"no geometry generator for noz_type={noz} (su2/geom/{noz}.py)")

    geo = run_dir / "mesh.geo"
    geo.write_text(gen.geo(case, source=str(case_path)))

    gmsh_log = run_dir / "gmsh.log"
    with open(gmsh_log, "w") as f:
        r = subprocess.run(["gmsh", str(geo), "-2", "-format", "su2",
                            "-o", str(run_dir / "mesh.su2")], stdout=f, stderr=subprocess.STDOUT)
    if r.returncode != 0:
        print("\n".join(gmsh_log.read_text().splitlines()[-10:]), file=sys.stderr)
        die(f"gmsh failed, see {gmsh_log}")

    with open(run_dir / "mesh.su2") as f:
        nelem = next((m.group(1) for line in f if (m := re.match(r"NELEM=\s*(\d+)", line))), "?")
    log(f"mesh: {nelem} cells")


def su2_config(case: dict, case_name: str) -> str:
    """Return the su2.cfg text for this case."""
    name = get(case, "case", "name")
    noz = get(case, "geometry", "noz_type")
    p0 = fmt(get(case, "gas", "plen_pres_pa"))
    T0 = fmt(get(case, "gas", "plen_temp_K"))
    pb = fmt(get(case, "su2", "back_pres_pa"))
    Tw = fmt(get(case, "su2", "wall_temp_K"))
    iters = get(case, "su2", "iterations")

    species = Path(get(case, "gas", "species_file")).stem
    if species not in GASES:
        die(f"no continuum gas properties for species '{species}'")
    gas = {k: fmt(v) for k, v in GASES[species].items()}

    match get(case, "su2", "faceplate", "wall"):
        case "wall":
            walls, syms, plot = f"wall, {Tw}, faceplate, {Tw}", "axis", "wall, faceplate"
        case "sym":
            walls, syms, plot = f"wall, {Tw}", "axis, faceplate", "wall"
        case _:
            die("su2.faceplate must be 'wall' or 'sym'")

    return f"""\
% Generated by su2/setup.py from {case_name} -- edit the case file, not this.
% Case: {name}, {noz}, {species}, p0 = {p0} Pa, T0 = {T0} K, p_back = {pb} Pa

% ---- problem ----------------------------------------------------------------
SOLVER= NAVIER_STOKES
KIND_TURB_MODEL= NONE
MATH_PROBLEM= DIRECT
AXISYMMETRIC= YES
RESTART_SOL= NO

% ---- freestream = initial state (quiescent chamber gas at back pressure) ------
REF_DIMENSIONALIZATION= DIMENSIONAL
INIT_OPTION= TD_CONDITIONS
FREESTREAM_OPTION= TEMPERATURE_FS
MACH_NUMBER= 0.01
AOA= 0.0
FREESTREAM_PRESSURE= {pb}
FREESTREAM_TEMPERATURE= {Tw}

% ---- gas --------------------------------------------------------------------
FLUID_MODEL= IDEAL_GAS
GAMMA_VALUE= {gas['gamma']}
GAS_CONSTANT= {gas['R']}
VISCOSITY_MODEL= SUTHERLAND
MU_REF= {gas['mu_ref']}
MU_T_REF= {gas['T_ref']}
SUTHERLAND_CONSTANT= {gas['S']}
CONDUCTIVITY_MODEL= CONSTANT_PRANDTL
PRANDTL_LAM= {gas['Pr']}

% ---- boundaries -------------------------------------------------------------
MARKER_ISOTHERMAL= ( {walls} )
MARKER_SYM= ( {syms} )
INLET_TYPE= TOTAL_CONDITIONS
MARKER_INLET= ( inlet, {T0}, {p0}, 1.0, 0.0, 0.0 )
MARKER_OUTLET= ( outlet, {pb} )
MARKER_PLOTTING= ( {plot} )
MARKER_MONITORING= ( {plot} )
MARKER_ANALYZE= ( inlet, outlet )
MARKER_ANALYZE_AVERAGE= MASSFLUX

% ---- numerics ---------------------------------------------------------------
NUM_METHOD_GRAD= WEIGHTED_LEAST_SQUARES
CONV_NUM_METHOD_FLOW= ROE
ENTROPY_FIX_COEFF= 0.05
MUSCL_FLOW= YES
SLOPE_LIMITER_FLOW= VENKATAKRISHNAN
VENKAT_LIMITER_COEFF= 0.05
TIME_DISCRE_FLOW= EULER_IMPLICIT
CFL_NUMBER= 1.0
CFL_ADAPT= YES
CFL_ADAPT_PARAM= ( 0.5, 1.2, 0.5, 100.0 )
LINEAR_SOLVER= FGMRES
LINEAR_SOLVER_PREC= ILU
LINEAR_SOLVER_ERROR= 1E-4
LINEAR_SOLVER_ITER= 20

% ---- convergence ------------------------------------------------------------
ITER= {iters}
CONV_FIELD= RMS_DENSITY
CONV_RESIDUAL_MINVAL= -10
CONV_STARTITER= 100

% ---- I/O --------------------------------------------------------------------
MESH_FILENAME= mesh.su2
MESH_FORMAT= SU2
SOLUTION_FILENAME= restart_flow.dat
RESTART_FILENAME= restart_flow.dat
OUTPUT_FILES= ( RESTART, PARAVIEW, SURFACE_CSV )
VOLUME_FILENAME= flow
SURFACE_FILENAME= surface_flow
CONV_FILENAME= history
VOLUME_OUTPUT= ( COORDINATES, SOLUTION, PRIMITIVE )
SCREEN_OUTPUT= ( INNER_ITER, WALL_TIME, RMS_DENSITY, RMS_ENERGY, AVG_CFL, SURFACE_MASSFLOW )
HISTORY_OUTPUT= ( ITER, RMS_RES, CFL_NUMBER, FLOW_COEFF )
OUTPUT_WRT_FREQ= 500
SCREEN_WRT_FREQ_INNER= 50
"""


def setup(case_path, runs_dir="runs") -> Path:
    """Create runs_dir/<case name>/su2/ with mesh and su2.cfg. Returns the run dir."""
    case_path = Path(case_path).resolve()
    case = load_case(case_path)

    name = get(case, "case", "name")
    if (get(case, "geometry", "dim"), get(case, "geometry", "symmetry")) != (2, "axial"):
        die("only dim=2, symmetry=axial is implemented so far")

    run_dir = Path(runs_dir) / name / "su2"
    run_dir.mkdir(parents=True, exist_ok=True)
    shutil.copy(case_path, run_dir / "case.toml")  # provenance: run dir records its inputs
    log(f"case {name} -> {run_dir}")

    write_mesh(case, case_path, run_dir)
    (run_dir / "su2.cfg").write_text(su2_config(case, case_path.name))
    log(f"wrote {run_dir / 'su2.cfg'}")
    return run_dir


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("case", nargs="?", default="config.toml", help="case file (default: config.toml)")
    ap.add_argument("--runs", default="runs", help="runs directory (default: ./runs)")
    args = ap.parse_args(argv)
    setup(args.case, args.runs)


if __name__ == "__main__":
    main()
