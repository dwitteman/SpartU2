#!/usr/bin/env bash
# Write a gmsh .geo for an axisymmetric capillary exhausting into a chamber.
# Usage: capillary.sh CASE.toml > mesh.geo
#
# x is the symmetry axis, y is radius, exit plane at x = 0. Units: metres.
#
#   P5 +--------------- top (outlet) --------------+ P4
#      |                                           |
#  faceplate              block B               outlet
#      |                                           |
#   P7 +---- tube wall ----+ P6 ------------------+ P8
#      |                   |                       |
#    inlet   tube block    |       block A       outlet
#      |                   |                       |
#   P1 +------ axis -------+ P2 ------ axis ------+ P3
#
# Markers: inlet, wall, faceplate, axis, outlet
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/../../lib/common.sh"

cfg=${1:?usage: capillary.sh CASE.toml}

D=$(calc "$(toml_get "$cfg" geometry throat_diam_mm) * 1e-3")
L=$(calc "$(toml_get "$cfg" geometry throat_length_mm) * 1e-3")
R=$(calc "$D / 2")
Lx=$(calc "$(toml_get "$cfg" geometry chamb_length_cm) * 1e-2") #chamged from ext_length_D,,
Rext=$(calc "$(toml_get "$cfg" geometry chamb_height_cm) * 1e-2")
h=$(calc "$(toml_get "$cfg" su2 first_cell_um) * 1e-6")
nr_t=$(toml_get "$cfg" su2 n_radial_tube)
nx_t=$(toml_get "$cfg" su2 n_axial_tube)
nx_e=$(toml_get "$cfg" su2 n_axial_ext)
nr_e=$(toml_get "$cfg" su2 n_radial_ext)

[[ $(calc "$Rext > $R") == 1 ]] || die "ext_radius_D must exceed 0.5"

# Every graded line is oriented so it starts at the fine end; gmsh then grows
# cell size by the progression factor along the line.
g_rt=$(growth_rate "$R" "$nr_t" "$h")
g_xt=$(growth_rate "$L" "$nx_t" "$h")
g_xe=$(growth_rate "$Lx" "$nx_e" "$h")
g_re=$(growth_rate "$(calc "$Rext - $R")" "$nr_e" "$h")

cat <<EOF
// Generated by su2/geom/capillary.sh from $cfg
// D = $D m, L = $L m, domain ${Lx} x ${Rext} m, first cell $h m
// growth: tube radial $g_rt, tube axial $g_xt, ext axial $g_xe, ext radial $g_re

Point(1) = {-$L, 0, 0};
Point(2) = {0, 0, 0};
Point(3) = {$Lx, 0, 0};
Point(4) = {$Lx, $Rext, 0};
Point(5) = {0, $Rext, 0};
Point(6) = {0, $R, 0};
Point(7) = {-$L, $R, 0};
Point(8) = {$Lx, $R, 0};

// tube (axial lines run exit -> inlet, radial lines run wall -> axis)
Line(1) = {2, 1};   // axis, tube
Line(2) = {6, 7};   // tube wall
Line(3) = {7, 1};   // inlet
Line(4) = {6, 2};   // exit plane
// block A (exit plane -> outlet, lip radius -> axis)
Line(5) = {2, 3};   // axis, chamber
Line(6) = {6, 8};   // lip line extension
Line(7) = {8, 3};   // outlet, lower
// block B (lip -> outer radius)
Line(8) = {6, 5};   // faceplate
Line(9) = {8, 4};   // outlet, upper
Line(10) = {5, 4};  // top

Curve Loop(1) = {-1, -4, 2, 3};
Curve Loop(2) = {5, -7, -6, 4};
Curve Loop(3) = {6, 9, -10, -8};
Plane Surface(1) = {1};
Plane Surface(2) = {2};
Plane Surface(3) = {3};

Transfinite Curve{3, 4, 7} = $((nr_t + 1)) Using Progression $g_rt;
Transfinite Curve{1, 2} = $((nx_t + 1)) Using Progression $g_xt;
Transfinite Curve{5, 6, 10} = $((nx_e + 1)) Using Progression $g_xe;
Transfinite Curve{8, 9} = $((nr_e + 1)) Using Progression $g_re;
Transfinite Surface{1, 2, 3};
Recombine Surface{1, 2, 3};

Physical Curve("inlet") = {3};
Physical Curve("wall") = {2};
Physical Curve("faceplate") = {8};
Physical Curve("axis") = {1, 5};
Physical Curve("outlet") = {7, 9, 10};
Physical Surface("fluid") = {1, 2, 3};
EOF
