#!/usr/bin/env bash
# Build an SU2 run directory from a case file: mesh + config.
# Usage: su2/setup.sh CASE.toml [RUNS_DIR]
# Creates RUNS_DIR/<case name>/su2/ (RUNS_DIR defaults to ./runs).
set -euo pipefail
here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
source "$here/../lib/common.sh"

cfg=$(realpath "${1:?usage: setup.sh CASE.toml [RUNS_DIR]}")
runs=${2:-runs}

name=$(toml_get "$cfg" case name)
noz=$(toml_get "$cfg" geometry noz_type)
dim=$(toml_get "$cfg" geometry dim)
sym=$(toml_get "$cfg" geometry symmetry)
[[ $dim == 2 && $sym == axial ]] || die "only dim=2, symmetry=axial is implemented so far"
geo_script="$here/geom/$noz.sh"
[[ -x $geo_script ]] || die "no geometry generator for noz_type=$noz ($geo_script)"

dir="$runs/$name/su2"
mkdir -p "$dir"
cp "$cfg" "$dir/case.toml"     # provenance: the run dir records its own inputs
log "case $name -> $dir"

# --- mesh -------------------------------------------------------------------
"$geo_script" "$cfg" > "$dir/mesh.geo"
gmsh "$dir/mesh.geo" -2 -format su2 -o "$dir/mesh.su2" > "$dir/gmsh.log" 2>&1 \
    || { tail "$dir/gmsh.log"; die "gmsh failed, see $dir/gmsh.log"; }
log "mesh: $(awk '/^NELEM=/ {print $2; exit}' "$dir/mesh.su2") cells"

# --- gas & boundary values ----------------------------------------------------
p0=$(toml_get "$cfg" gas plen_pres_pa)
T0=$(toml_get "$cfg" gas plen_temp_K)
pb=$(toml_get "$cfg" su2 back_pres_pa)
Tw=$(toml_get "$cfg" su2 wall_temp_K)
iters=$(toml_get "$cfg" su2 iterations)
species=$(basename "$(toml_get "$cfg" gas species_file)" .species)

# Continuum gas properties. Sutherland fits matched to the DSMC VHS/VSS models
# near room temperature.
case $species in
    he) gamma=1.666667; Rgas=2077.1;  mu_ref=1.865e-5; T_ref=273.15; S=79.4; Pr=0.667 ;;
    ar) gamma=1.666667; Rgas=208.13;  mu_ref=2.125e-5; T_ref=273.15; S=144;  Pr=0.667 ;;
    *)  die "no continuum gas properties for species '$species'" ;;
esac

case $(toml_get "$cfg" su2 faceplate wall) in
    wall) walls="wall, $Tw, faceplate, $Tw"; syms="axis"; plot="wall, faceplate" ;;
    sym)  walls="wall, $Tw";                 syms="axis, faceplate"; plot="wall" ;;
    *)    die "su2.faceplate must be 'wall' or 'sym'" ;;
esac

cat > "$dir/su2.cfg" <<EOF
% Generated by su2/setup.sh from $(basename "$cfg") -- edit the case file, not this.
% Case: $name, $noz, $species, p0 = $p0 Pa, T0 = $T0 K, p_back = $pb Pa

% ---- problem ----------------------------------------------------------------
SOLVER= NAVIER_STOKES
KIND_TURB_MODEL= NONE
MATH_PROBLEM= DIRECT
AXISYMMETRIC= YES
RESTART_SOL= NO

% ---- freestream = initial state (quiescent chamber gas at back pressure) ------
REF_DIMENSIONALIZATION= DIMENSIONAL
INIT_OPTION= TD_CONDITIONS
FREESTREAM_OPTION= TEMPERATURE_FS
MACH_NUMBER= 0.01
AOA= 0.0
FREESTREAM_PRESSURE= $pb
FREESTREAM_TEMPERATURE= $Tw

% ---- gas --------------------------------------------------------------------
FLUID_MODEL= IDEAL_GAS
GAMMA_VALUE= $gamma
GAS_CONSTANT= $Rgas
VISCOSITY_MODEL= SUTHERLAND
MU_REF= $mu_ref
MU_T_REF= $T_ref
SUTHERLAND_CONSTANT= $S
CONDUCTIVITY_MODEL= CONSTANT_PRANDTL
PRANDTL_LAM= $Pr

% ---- boundaries -------------------------------------------------------------
MARKER_ISOTHERMAL= ( $walls )
MARKER_SYM= ( $syms )
INLET_TYPE= TOTAL_CONDITIONS
MARKER_INLET= ( inlet, $T0, $p0, 1.0, 0.0, 0.0 )
MARKER_OUTLET= ( outlet, $pb )
MARKER_PLOTTING= ( $plot )
MARKER_MONITORING= ( $plot )
MARKER_ANALYZE= ( inlet, outlet )
MARKER_ANALYZE_AVERAGE= MASSFLUX

% ---- numerics ---------------------------------------------------------------
NUM_METHOD_GRAD= WEIGHTED_LEAST_SQUARES
CONV_NUM_METHOD_FLOW= ROE
ENTROPY_FIX_COEFF= 0.05
MUSCL_FLOW= YES
SLOPE_LIMITER_FLOW= VENKATAKRISHNAN
VENKAT_LIMITER_COEFF= 0.05
TIME_DISCRE_FLOW= EULER_IMPLICIT
CFL_NUMBER= 1.0
CFL_ADAPT= YES
CFL_ADAPT_PARAM= ( 0.5, 1.2, 0.5, 100.0 )
LINEAR_SOLVER= FGMRES
LINEAR_SOLVER_PREC= ILU
LINEAR_SOLVER_ERROR= 1E-4
LINEAR_SOLVER_ITER= 20

% ---- convergence ------------------------------------------------------------
ITER= $iters
CONV_FIELD= RMS_DENSITY
CONV_RESIDUAL_MINVAL= -10
CONV_STARTITER= 100

% ---- I/O --------------------------------------------------------------------
MESH_FILENAME= mesh.su2
MESH_FORMAT= SU2
SOLUTION_FILENAME= restart_flow.dat
RESTART_FILENAME= restart_flow.dat
OUTPUT_FILES= ( RESTART, PARAVIEW, SURFACE_CSV )
VOLUME_FILENAME= flow
SURFACE_FILENAME= surface_flow
CONV_FILENAME= history
VOLUME_OUTPUT= ( COORDINATES, SOLUTION, PRIMITIVE )
SCREEN_OUTPUT= ( INNER_ITER, WALL_TIME, RMS_DENSITY, RMS_ENERGY, AVG_CFL, SURFACE_MASSFLOW )
HISTORY_OUTPUT= ( ITER, RMS_RES, CFL_NUMBER, FLOW_COEFF )
OUTPUT_WRT_FREQ= 500
SCREEN_WRT_FREQ_INNER= 50
EOF
log "wrote $dir/su2.cfg"
